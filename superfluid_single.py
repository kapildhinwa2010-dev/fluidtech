def _build_package():
    """Materialise the `superfluid` package inside sys.modules."""
    pkg = types.ModuleType("superfluid")
    pkg.__path__ = []
    pkg.__package__ = "superfluid"
    sys.modules["superfluid"] = pkg
    blocks = {}
    cur = None
    for line in _SOURCES.splitlines():
        if line.startswith("#--- FILE: "):
            # "#--- FILE: <path> ---"  ->  "<path>"
            cur = line[len("#--- FILE: "):].split(" ---")[0].strip()
            blocks[cur] = []
        elif cur is not None:
            blocks[cur].append(line)
    order = [p for p in blocks if not p.endswith("/__init__.py")]
    order += [p for p in blocks if p.endswith("/__init__.py")]
    for path in order:
        lines = blocks[path]
        if path.endswith("selftest.py"):
            continue
        if path.endswith("/__init__.py"):
            # the package __init__ re-exports the public API; run it LAST so
            # that every submodule already exists in sys.modules
            exec(compile("\n".join(lines), path, "exec"), pkg.__dict__)
            continue
        name = path.split("/")[-1][:-3]
        mod = types.ModuleType("superfluid." + name)
        mod.__package__ = "superfluid"
        sys.modules["superfluid." + name] = mod
        exec(compile("\n".join(lines), path, "exec"), mod.__dict__)
        setattr(pkg, name, mod)
    return pkg, blocks


